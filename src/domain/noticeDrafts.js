/** まだ出していない下書きか。出したお知らせには fromDraft が入る。 */
export const draftAlreadySent = (notices, draftId) =>
    (notices || []).some(n => n && n.fromDraft === draftId);

/** 下書き一覧(新しい順)。出し済みも消さずに出す ― 「前に出したっけ？」を画面で確かめられるように。 */
export const sortedDrafts = (drafts = NOTICE_DRAFTS) =>
    (drafts || []).slice().sort((a, b) => String(b?.shipped || '').localeCompare(String(a?.shipped || '')));

/** 隠した下書きの id 一覧。⚠端末ローカルに置かない(他の端末では消えていないことになる)。 */
export const hiddenDraftIds = (shared) => {
  const v = shared && shared.appNoticeConfig && shared.appNoticeConfig.hiddenDrafts;
  return Array.isArray(v) ? v.filter(x => typeof x === 'string') : [];
};

/**
 * 隠す / 戻す を反映した新しい一覧を返す。
 * ⚠配列の追記は後勝ちで消える。呼び出し側は **この関数が返した配列をそのまま** 保存すること。
 */
export const withHiddenDraft = (shared, id, hide) => {
  const cur = new Set(hiddenDraftIds(shared));
  if (hide) cur.add(String(id)); else cur.delete(String(id));
  return [...cur];
};

/** 画面に出す下書き(隠した物を除く)。 */
export const visibleDrafts = (shared, drafts = NOTICE_DRAFTS) => {
  const hidden = new Set(hiddenDraftIds(shared));
  return sortedDrafts(drafts).filter(d => d && !hidden.has(d.id));
};
